"""Per-operation traces of model and tool calls, plus a live event feed for streaming.

A Tracer is installed in a context variable for the duration of one AI operation, so model calls
made deep inside services (e.g. a briefing generated by an agent tool) join the same trace.
"""

import json
import logging
import time
from collections.abc import Callable, Iterator
from contextlib import contextmanager
from contextvars import ContextVar
from hashlib import sha256
from typing import Any
from uuid import UUID

from sqlmodel import Session

from customer_intelligence.core.errors import WorkflowError
from customer_intelligence.models.trace import AgentSpan, AgentTrace

logger = logging.getLogger(__name__)
_current: ContextVar["Tracer | None"] = ContextVar("agent_tracer", default=None)

Listener = Callable[[dict[str, Any]], None]


def current_tracer() -> "Tracer | None":
    return _current.get()


def _total(values: list[int | None]) -> int | None:
    known = [value for value in values if value is not None]
    return sum(known) if known else None


class Tracer:
    def __init__(
        self,
        kind: str,
        *,
        dataset_id: UUID | None = None,
        conversation_id: UUID | None = None,
        prompt_version: str | None = None,
        listener: Listener | None = None,
    ) -> None:
        self.trace = AgentTrace(
            kind=kind,
            dataset_id=dataset_id,
            conversation_id=conversation_id,
            prompt_version=prompt_version,
        )
        self.spans: list[AgentSpan] = []
        self.listener = listener
        self._parent: str | None = None
        self._started = time.monotonic()

    @property
    def id(self) -> UUID:
        return self.trace.id

    @property
    def model_calls(self) -> int:
        return sum(span.kind == "model" for span in self.spans)

    def emit(self, event: dict[str, Any]) -> None:
        if self.listener is None:
            return
        try:
            self.listener({"trace_id": str(self.id), **event})
        except Exception:  # a disconnected stream must never break the operation
            logger.debug("Trace listener failed", exc_info=True)

    def _add(self, **fields: Any) -> AgentSpan:
        span = AgentSpan(trace_id=self.id, sequence=len(self.spans) + 1, **fields)
        self.spans.append(span)
        return span

    def model_started(self, name: str, model: str) -> None:
        self.emit({"type": "model_start", "name": name, "model": model, "parent": self._parent})

    def record_model(self, **fields: Any) -> AgentSpan:
        span = self._add(kind="model", parent=self._parent, **fields)
        self.emit(
            {
                "type": "model_end",
                "name": span.name,
                "model": span.model,
                "status": span.status,
                "duration_ms": span.duration_ms,
                "input_tokens": span.input_tokens,
                "output_tokens": span.output_tokens,
                "attempts": span.attempts,
            }
        )
        return span

    @contextmanager
    def tool(self, name: str, arguments: dict[str, Any] | None = None) -> Iterator[dict[str, Any]]:
        """Record a tool execution.

        The caller may set `evidence_path`, or `error_code` for a handled failure, on the
        yielded dict.
        """
        encoded = json.dumps(arguments or {}, sort_keys=True, default=str)
        outcome: dict[str, Any] = {"evidence_path": None}
        self.emit({"type": "tool_start", "name": name})
        started = time.monotonic()
        previous, self._parent = self._parent, name
        status, error_code = "succeeded", None
        try:
            yield outcome
        except BaseException as exc:
            status = "failed"
            error_code = exc.code if isinstance(exc, WorkflowError) else "internal_error"
            raise
        finally:
            self._parent = previous
            if outcome.get("error_code") and status == "succeeded":
                status, error_code = "failed", outcome["error_code"]
            span = self._add(
                kind="tool",
                name=name,
                status=status,
                error_code=error_code,
                duration_ms=round((time.monotonic() - started) * 1000),
                arguments_sha256=sha256(encoded.encode()).hexdigest(),
                evidence_path=outcome["evidence_path"],
                detail={"arguments": arguments} if len(encoded) <= 2000 else {},
            )
            self.emit(
                {
                    "type": "tool_end",
                    "name": name,
                    "status": status,
                    "duration_ms": span.duration_ms,
                    "evidence_path": span.evidence_path,
                }
            )

    def finish(self, status: str, error_code: str | None = None) -> AgentTrace:
        models = [span for span in self.spans if span.kind == "model"]
        trace = self.trace
        trace.status = status
        trace.error_code = error_code
        trace.model_calls = len(models)
        trace.tool_calls = sum(span.kind == "tool" for span in self.spans)
        trace.retries = sum(span.attempts - 1 for span in models)
        trace.input_tokens = _total([span.input_tokens for span in models])
        trace.output_tokens = _total([span.output_tokens for span in models])
        costs = [span.cost_usd for span in models]
        # A partial cost would understate spend, so report it only when every call is priced.
        trace.cost_usd = (
            round(sum(c for c in costs if c is not None), 6)
            if models and None not in costs
            else None
        )
        trace.duration_ms = round((time.monotonic() - self._started) * 1000)
        return trace

    def persist(self, session: Session) -> None:
        try:
            session.add(self.trace)
            session.add_all(self.spans)
            session.commit()
        except Exception:
            session.rollback()
            logger.warning("Could not save agent trace %s", self.id, exc_info=True)


@contextmanager
def traced(session: Session, kind: str, **fields: Any) -> Iterator[Tracer]:
    """Trace one operation and save it even when the operation fails.

    Nested use joins the active trace instead of starting another.
    """
    active = _current.get()
    if active is not None:
        yield active
        return
    from customer_intelligence.services.autonomy import check_ai_allowed

    check_ai_allowed(session)  # kill switch and daily token budget, before any model call
    tracer = Tracer(kind, **fields)
    token = _current.set(tracer)
    try:
        yield tracer
    except BaseException as exc:
        _current.reset(token)
        tracer.finish("failed", exc.code if isinstance(exc, WorkflowError) else "internal_error")
        session.rollback()
        tracer.persist(session)
        raise
    _current.reset(token)
    tracer.finish("succeeded")
    # A successful operation that made no calls (e.g. an idempotent replay) has nothing to show.
    if tracer.spans:
        tracer.persist(session)
